"""SECURITY.md links, provenance footer, and citation warnings. No network."""

import json
import re
from datetime import date
from pathlib import Path

import pytest

from asgard.cli.main import main
from asgard.core.config import ConfigError, load_run
from asgard.core.events import CitationWarning, StageFinished
from asgard.core.stage import RunContext
from asgard.core.stages.security_md import SecurityMdStage
from asgard.providers.models import LLMSettings, RoleSpec

_GUIDELINE = """\
# app Security Policy — User Guidelines

## 1. Authentication

**REC-01 — Reject unsigned tokens.**
Reject unsigned tokens. (#12, #34)
"""


def _settings() -> LLMSettings:
    return LLMSettings(
        default=RoleSpec(provider="fake", model="fallback"),
        classifier=RoleSpec(provider="fake", model="class-model"),
        evaluator=RoleSpec(provider="ollama", model="eval-model"),
        synthesizer=RoleSpec(provider="fake", model="synth-model"),
    )


def _prepare(tmp_path: Path, pr_ids: list[str], *, analysed: int = 4) -> None:
    directory = tmp_path / "consolidate"
    directory.mkdir(parents=True)
    records = [
        {
            "pr_id": pr_id,
            "title": "Fix",
            "link": f"https://github.com/acme/app/pull/{pr_id}",
            "evidence": [{"quote": "bypass", "location": "description"}],
            "rationale": "security",
        }
        for pr_id in pr_ids
    ]
    (directory / "output.json").write_text(json.dumps(records), encoding="utf-8")
    summary = {"total": analysed, "security": len(pr_ids), "non_security": 0, "unresolved": 0}
    (directory / "summary.json").write_text(json.dumps(summary), encoding="utf-8")


def _stage(path: Path | None = None) -> SecurityMdStage:
    return SecurityMdStage(
        "acme/app",
        _settings(),
        path=path,
        clock=lambda: date(2026, 10, 14),
    )


def _run(
    tmp_path: Path,
    guideline: str,
    *,
    path: Path | None = None,
) -> tuple[dict[str, object], list[object], str]:
    events: list[object] = []
    stage = _stage(path)
    manifest = stage.run(RunContext(tmp_path, events.append), guideline)
    written = Path(str(manifest["path"])).read_text(encoding="utf-8")
    return manifest, events, written


def test_citations_become_links_and_the_footer_records_the_run(tmp_path: Path) -> None:
    _prepare(tmp_path, ["12", "34"])
    manifest, events, written = _run(tmp_path, _GUIDELINE)
    assert manifest["unknown_citations"] == []
    assert not any(isinstance(event, CitationWarning) for event in events)
    assert "[#12](https://github.com/acme/app/pull/12)" in written
    assert "[#34](https://github.com/acme/app/pull/34)" in written
    assert re.search(r"(?<!\[)#\d+", written) is None
    assert "Generated by ASGARD 0.1.0 on 2026-10-14 for acme/app." in written
    assert (
        "Models: classifier fake/class-model, evaluator ollama/eval-model, "
        "synthesizer fake/synth-model."
    ) in written
    assert "Pull requests analysed: 4. Security pull requests used: 2." in written
    assert Path(str(manifest["path"])) == tmp_path / "SECURITY.md"
    saved = json.loads((tmp_path / "security_md" / "output.json").read_text(encoding="utf-8"))
    assert saved == manifest

    events.clear()
    again = _stage().run(RunContext(tmp_path, events.append), _GUIDELINE)
    assert again == manifest
    assert events == [StageFinished(stage="security_md", skipped=True)]


def test_pkcs_hash_is_not_a_pull_request_citation(tmp_path: Path) -> None:
    _prepare(tmp_path, ["132"])
    guideline = (
        "Prefer RSASSA-PSS over PKCS #1 v1.5 because the padding is randomized. (#132)\n"
    )
    manifest, events, written = _run(tmp_path, guideline)
    assert manifest["unknown_citations"] == []
    assert not any(isinstance(event, CitationWarning) for event in events)
    assert "PKCS #1 v1.5" in written
    assert "pull/1)" not in written
    assert "[#132](https://github.com/acme/app/pull/132)" in written


def test_unknown_citation_is_linked_and_reported(tmp_path: Path) -> None:
    _prepare(tmp_path, ["12"])
    guideline = _GUIDELINE.replace(
        "(#12, #34)",
        "(#12, #34, #3, #34)\n\nSee [#99](https://github.com/acme/app/pull/99).",
    )
    manifest, events, written = _run(tmp_path, guideline)
    warnings = [event for event in events if isinstance(event, CitationWarning)]
    assert [event.pr_id for event in warnings] == ["3", "34", "99"]
    assert [event.message for event in warnings] == [
        "citation #3 is not in the approved security set",
        "citation #34 is not in the approved security set",
        "citation #99 is not in the approved security set",
    ]
    assert manifest["unknown_citations"] == ["3", "34", "99"]
    assert "[#3](https://github.com/acme/app/pull/3)" in written
    assert "[#12](https://github.com/acme/app/pull/12)" in written
    assert "[#34](https://github.com/acme/app/pull/34)" in written
    assert written.count("[#99](https://github.com/acme/app/pull/99)") == 1
    assert re.search(r"(?<!\[)#\d+", written) is None


def test_custom_path_and_rejected_input(tmp_path: Path) -> None:
    _prepare(tmp_path, [], analysed=1)
    target = tmp_path / "nested" / "policy.md"
    manifest, events, written = _run(
        tmp_path,
        "There was no security discussion, so there is no guideline.",
        path=target,
    )
    assert target.is_file()
    assert manifest["path"] == str(target)
    assert manifest["unknown_citations"] == []
    assert not any(isinstance(event, CitationWarning) for event in events)
    assert "Security pull requests used: 0." in written
    assert "Pull requests analysed: 1." in written
    assert not (tmp_path / "SECURITY.md").exists()

    (tmp_path / "security_md" / "output.json").unlink()
    with pytest.raises(ConfigError, match="synthesized guideline"):
        _stage().run(RunContext(tmp_path, lambda _event: None), ["12"])


def test_config_accepts_a_security_md_path(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("GITHUB_TOKEN", "ghp_test")
    target = tmp_path / "policy.md"
    source = tmp_path / "asgard.toml"
    source.write_text(
        "\n".join(
            [
                'repo = "acme/app"',
                f'output_dir = "{tmp_path / "run"}"',
                f'security_md = "{target}"',
                "",
                "[llm.default]",
                'provider = "fake"',
                'model = "fake"',
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    config, _ = load_run(source)
    assert config.security_md == target


def test_help_lists_the_stage_and_the_path_flag(capsys: pytest.CaptureFixture[str]) -> None:
    with pytest.raises(SystemExit) as caught:
        main(["run", "--help"])
    assert caught.value.code == 0
    text = capsys.readouterr().out
    assert "--security-md" in text
    assert "security_md" in text
