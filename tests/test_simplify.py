_FOOTER = (
    "---\n"
    "\n"
    "Generated by ASGARD 0.1.0 on 2026-10-14 for acme/app.\n"
    "Models: classifier fake/class-model, evaluator fake/class-model, "
    "synthesizer fake/class-model.\n"
    "Pull requests analysed: 1. Security pull requests used: 1.\n"
)
_ORIGINAL = "# Security\n\nCheck the login flow (#12).\n\n" + _FOOTER
_PLAIN = (
    "# Security\n\n"
    "Check the login flow (#12).\n\n"
    "Broken Access Control is about who can reach a feature. "
    "This matters because the login flow was discussed in the cited pull request.\n"
    "\n---\n\nGenerated by ASGARD 9.9.9 on 1999-01-01 for elsewhere.\n"
)
_PLAIN_AGAIN = (
    "# Security\n\n"
    "Check the login flow (#12).\n\n"
    "A shorter explanation of the same recommendation (#12).\n"
)
_WITH_EXTRA = "# Security\n\nCheck the login flow (#12) and also invent one (#99).\n"


def _settings(**extra: Any) -> LLMSettings:
    llm: dict[str, Any] = {"default": {"provider": "fake", "model": "class-model"}}
    llm.update(extra)
    return LLMSettings.model_validate(llm)


def _factory(handler: FakeHandler, settings: LLMSettings | None = None) -> LLMFactory:
    return LLMFactory(
        settings or _settings(),
        Credentials(),
        handlers={"fake": handler},
        sleep=lambda _: None,
    )


def _run(root: Path, *, manifest: bool = False, llm: dict[str, Any] | None = None) -> Path:
    root.mkdir(parents=True, exist_ok=True)
    payload: dict[str, Any] = {
        "repo": "acme/app",
        "llm": llm or {"default": {"provider": "fake", "model": "class-model"}},
        "output_dir": str(root),
    }
    (root / "config.json").write_text(json.dumps(payload), encoding="utf-8")
    (root / "SECURITY.md").write_text(_ORIGINAL, encoding="utf-8")
    if manifest:
        (root / "manifest.json").write_text(
            json.dumps(
                {
                    "prompts": {"classifier": "abc"},
                    "models": {"classifier": {"provider": "fake", "model": "class-model"}},
                    "files": {"SECURITY.md": "Security guideline."},
                }
            ),
            encoding="utf-8",
        )
        bundle = root / "bundle"
        bundle.mkdir()
        (bundle / "output.json").write_text(
            (root / "manifest.json").read_text(encoding="utf-8"),
            encoding="utf-8",
        )
    return root


def _events(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    if not path.is_file():
        return rows
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line:
            continue
        event = json.loads(line)
        event.pop("at", None)
        rows.append(event)
    return rows


def test_simplifier_falls_back_to_the_synthesizer_model() -> None:
    settings = _settings(synthesizer={"provider": "fake", "model": "synth-model"})
    assert settings.resolve("simplifier") == RoleSpec(provider="fake", model="synth-model")
    bare = _settings()
    assert bare.resolve("simplifier") == bare.resolve("synthesizer") == bare.default


def test_simplify_keeps_the_original_and_warns_on_new_citations(tmp_path: Path) -> None:
    assert "simplify" not in PIPELINE
    root = _run(tmp_path / "run", manifest=True)
    before = (root / "SECURITY.md").read_bytes()
    manifest_before = json.loads((root / "manifest.json").read_text(encoding="utf-8"))
    assert "simplifier" not in manifest_before["prompts"]
    assert "simplifier" not in manifest_before["models"]

    handler = FakeHandler([_WITH_EXTRA])
    destination = simplify_security_md(root, _factory(handler))

    assert destination == root / "SECURITY.simplified.md"
    assert (root / "SECURITY.md").read_bytes() == before
    assert len(handler.calls) == 1
    assert handler.calls[0][0].content == SYSTEM_PROMPT
    written = destination.read_text(encoding="utf-8")
    assert _FOOTER.strip() in written
    assert written.rstrip().endswith("Simplified by fake/class-model.")
    assert "(#99)" not in written
    assert "[#99](https://github.com/acme/app/pull/99)" in written
    assert "[#12](https://github.com/acme/app/pull/12)" in written
    warnings = [
        event for event in _events(root / "events.jsonl") if event["type"] == "CitationWarning"
    ]
    assert warnings == [
        {
            "type": "CitationWarning",
            "pr_id": "99",
            "message": "citation #99 is not in the original SECURITY.md",
        }
    ]

    saved = json.loads((root / "manifest.json").read_text(encoding="utf-8"))
    copied = json.loads((root / "bundle" / "output.json").read_text(encoding="utf-8"))
    assert saved == copied
    assert saved["prompts"]["simplifier"] == content_sha256(SYSTEM_PROMPT)
    assert saved["models"]["simplifier"] == {"provider": "fake", "model": "class-model"}
    assert saved["files"]["SECURITY.simplified.md"].startswith("Didactic rewrite")
    assert "simplify/output.json" in saved["files"]
    output = json.loads((root / "simplify" / "output.json").read_text(encoding="utf-8"))
    assert output["unknown_citations"] == ["99"]
    assert output["model"] == {"provider": "fake", "model": "class-model"}


def test_running_again_replaces_only_the_simplified_file(tmp_path: Path) -> None:
    root = _run(tmp_path / "run")
    before = (root / "SECURITY.md").read_bytes()
    handler = FakeHandler([_PLAIN, _PLAIN_AGAIN])
    factory = _factory(handler)

    first = simplify_security_md(root, factory)
    first_text = first.read_text(encoding="utf-8")
    assert "shorter explanation" not in first_text
    assert first_text.count("Generated by ASGARD") == 1
    assert "0.1.0" in first_text
    assert "9.9.9" not in first_text
    second = simplify_security_md(root, factory)

    assert second == first
    assert "shorter explanation" in second.read_text(encoding="utf-8")
    assert (root / "SECURITY.md").read_bytes() == before
    assert len(handler.calls) == 2
    assert not (root / "classify").exists()
    assert not (root / "synthesize").exists()


def test_bundle_records_the_simplifier_only_after_the_file_exists(tmp_path: Path) -> None:
    root = _run(tmp_path / "run")
    (root / "events.jsonl").write_text("", encoding="utf-8")
    first = BundleStage().run(RunContext(root, lambda _event: None), None)
    assert isinstance(first, dict)
    assert "simplifier" not in first["prompts"]
    assert "simplifier" not in first["models"]
    assert "SECURITY.simplified.md" not in first["files"]

    (root / "SECURITY.simplified.md").write_text("already simplified\n", encoding="utf-8")
    (root / "bundle" / "output.json").unlink()
    second = BundleStage().run(RunContext(root, lambda _event: None), None)
    assert isinstance(second, dict)
    assert second["prompts"]["simplifier"] == content_sha256(SYSTEM_PROMPT)
    assert second["models"]["simplifier"] == {"provider": "fake", "model": "class-model"}
    assert "SECURITY.simplified.md" in second["files"]


def test_cli_and_ui_write_the_same_file(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.chdir(tmp_path)
    root = _run(tmp_path / "runs" / "acme__app" / "20261016T120000Z", manifest=True)
    before = (root / "SECURITY.md").read_bytes()
    script = _PLAIN

    main(["simplify", str(root)], handlers={"fake": FakeHandler([script])})
    cli_bytes = (root / "SECURITY.simplified.md").read_bytes()
    assert (root / "SECURITY.md").read_bytes() == before
    (root / "SECURITY.simplified.md").unlink()
    (root / "simplify" / "output.json").unlink()

    app = create_app(handlers={"fake": FakeHandler([script])}, dotenv=None)
    client = TestClient(app)
    run_id = "acme__app--20261016T120000Z"
    response = client.post(f"/api/runs/{run_id}/simplify")
    assert response.status_code == 200, response.text
    deadline = time.monotonic() + 10
    while time.monotonic() < deadline:
        status = client.get(f"/api/runs/{run_id}").json()
        if not status["running"]:
            break
        time.sleep(0.05)
    else:
        raise AssertionError("simplify did not finish")
    assert status["error"] is None
    ui_bytes = (root / "SECURITY.simplified.md").read_bytes()
    assert ui_bytes == cli_bytes
    assert (root / "SECURITY.md").read_bytes() == before
    fetched = client.get(f"/api/runs/{run_id}/SECURITY.simplified.md")
    assert fetched.status_code == 200
    assert fetched.text.encode("utf-8") == cli_bytes
