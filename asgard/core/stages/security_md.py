"""Write SECURITY.md with pull request links and a provenance footer."""

import json
import re
from collections.abc import Callable
from datetime import date, datetime, timezone
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path
from typing import Any

from asgard.core.config import ConfigError
from asgard.core.events import CitationWarning
from asgard.core.stage import RunContext, Stage
from asgard.providers.models import LLMSettings

_INPUT = "security_md stage requires the synthesized guideline"
_SET = "approved security pull requests are missing"
_SUMMARY = "consolidation summary is missing"
_ROLES = ("classifier", "evaluator", "synthesizer")
_GROUP = re.compile(r"\((#\d+(?:\s*,\s*#\d+)*)\)")
_LINKED = re.compile(r"\[#(\d+)\]\(")
_ID = re.compile(r"#(\d+)")


class SecurityMdStage(Stage):
    name = "security_md"

    def __init__(
        self,
        repo: str,
        llm: LLMSettings,
        *,
        path: Path | None = None,
        clock: Callable[[], date] | None = None,
    ) -> None:
        self.repo = repo
        self.llm = llm
        self.path = path
        self.clock = clock or _utc_today

    def execute(self, ctx: RunContext, data: Any) -> dict[str, Any]:
        guideline = _guideline(data)
        approved = _approved(ctx)
        analysed = _analysed(ctx)
        unknown = sorted(
            {pr_id for pr_id in _cited(guideline) if pr_id not in approved},
            key=int,
        )
        for pr_id in unknown:
            ctx.emit(
                CitationWarning(
                    pr_id=pr_id,
                    message=f"citation #{pr_id} is not in the approved security set",
                )
            )
        body = _linkify(guideline, self.repo).rstrip() + "\n\n" + _footer(
            self.repo,
            self.llm,
            analysed,
            len(approved),
            self.clock(),
        )
        destination = self.path if self.path is not None else ctx.run_dir / "SECURITY.md"
        _replace(destination, body)
        return {"path": str(destination), "unknown_citations": unknown}


def _guideline(data: Any) -> str:
    if not isinstance(data, str):
        raise ConfigError(_INPUT)
    return data


def _approved(ctx: RunContext) -> set[str]:
    path = ctx.run_dir / "consolidate" / "output.json"
    data = _read(path, _SET)
    if not isinstance(data, list):
        raise ConfigError(_SET)
    approved: set[str] = set()
    for raw in data:
        if not isinstance(raw, dict):
            raise ConfigError(_SET)
        pr_id = raw.get("pr_id")
        if not isinstance(pr_id, str) or not pr_id:
            raise ConfigError(_SET)
        if pr_id in approved:
            raise ConfigError(f"duplicate pull request {pr_id}")
        approved.add(pr_id)
    return approved


def _analysed(ctx: RunContext) -> int:
    path = ctx.run_dir / "consolidate" / "summary.json"
    data = _read(path, _SUMMARY)
    total = data.get("total") if isinstance(data, dict) else None
    if isinstance(total, bool) or not isinstance(total, int) or total < 0:
        raise ConfigError(_SUMMARY)
    return total


def _read(path: Path, message: str) -> Any:
    if not path.is_file():
        raise ConfigError(message)
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        raise ConfigError(message) from None


def _cited(markdown: str) -> list[str]:
    cited: list[str] = []
    for match in _GROUP.finditer(markdown):
        cited.extend(_ID.findall(match.group(1)))
    cited.extend(_LINKED.findall(markdown))
    return cited


def _linkify(markdown: str, repo: str) -> str:
    def replace(match: re.Match[str]) -> str:
        body = _ID.sub(lambda item: _link(repo, item.group(1)), match.group(1))
        return f"({body})"

    return _GROUP.sub(replace, markdown)


def _link(repo: str, pr_id: str) -> str:
    return f"[#{pr_id}](https://github.com/{repo}/pull/{pr_id})"


def _footer(repo: str, llm: LLMSettings, analysed: int, used: int, day: date) -> str:
    models = []
    for role in _ROLES:
        spec = llm.resolve(role)
        models.append(f"{role} {spec.provider}/{spec.model}")
    return (
        "---\n"
        "\n"
        f"Generated by ASGARD {_package_version()} on {day.isoformat()} for {repo}.\n"
        f"Models: {', '.join(models)}.\n"
        f"Pull requests analysed: {analysed}. Security pull requests used: {used}.\n"
    )


def _package_version() -> str:
    try:
        return version("asgard")
    except PackageNotFoundError:
        return "0.1.0"


def _utc_today() -> date:
    return datetime.now(timezone.utc).date()


def _replace(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(path)
