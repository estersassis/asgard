"""Optional plain-language rewrite of a finished SECURITY.md.

Not part of the default pipeline. The CLI and the Guideline screen both call
``simplify_security_md``. The original file is never overwritten.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pydantic import ValidationError

from asgard.core.config import ConfigError
from asgard.core.events import CitationWarning
from asgard.core.prompt_registry import content_sha256, resolve_system_prompt
from asgard.core.sinks import JSONLSink
from asgard.core.stages.security_md import _cited, _linkify, _replace
from asgard.providers.factory import LLMFactory
from asgard.providers.models import LLMSettings, Message, RoleSpec

SIMPLIFIED_NAME = "SECURITY.simplified.md"
SIMPLIFY_OUTPUT = "simplify/output.json"
SIMPLIFIED_DESC = "Didactic rewrite of SECURITY.md. The original file is unchanged."
SIMPLIFY_OUTPUT_DESC = (
    "Path of SECURITY.simplified.md, the simplifier model, and citation warnings."
)

_MISSING = "SECURITY.md is missing"
_CONFIG = "run configuration is missing"
_INVALID = "run configuration is invalid"
_MANIFEST = "run manifest is invalid"


def simplify_security_md(run_dir: Path, factory: LLMFactory) -> Path:
    """Rewrite ``SECURITY.md`` into ``SECURITY.simplified.md`` with one model call."""
    run_dir = Path(run_dir)
    original_path = run_dir / "SECURITY.md"
    if not original_path.is_file():
        raise ConfigError(_MISSING)
    original = original_path.read_text(encoding="utf-8")
    config = _config(run_dir)
    repo = config.get("repo")
    if not isinstance(repo, str) or repo.count("/") != 1 or not repo.strip():
        raise ConfigError(_INVALID)
    settings = _settings(config)
    spec = settings.resolve("simplifier")
    prompt = resolve_system_prompt("simplifier", config, run_dir)
    source_body, provenance = _split(original)
    response = factory.generate(
        "simplifier",
        [
            Message(role="system", content=prompt),
            Message(role="user", content=source_body.strip()),
        ],
    )
    rewritten = _linkify(_model_body(response.text), repo)
    text = _assemble(rewritten, provenance, spec)
    allowed = set(_cited(original))
    unknown = sorted((item for item in _cited(text) if item not in allowed), key=int)
    destination = run_dir / SIMPLIFIED_NAME
    _replace(destination, text)
    _replace(
        run_dir / SIMPLIFY_OUTPUT,
        json.dumps(
            {
                "path": str(destination),
                "unknown_citations": unknown,
                "prompt_sha256": content_sha256(prompt),
                "model": {"provider": spec.provider, "model": spec.model},
            }
        ),
    )
    sink = JSONLSink(run_dir / "events.jsonl")
    for pr_id in unknown:
        sink.handle(
            CitationWarning(
                pr_id=pr_id,
                message=f"citation #{pr_id} is not in the original SECURITY.md",
            )
        )
    _update_manifest(run_dir, config)
    return destination


def apply_simplifier_manifest(
    manifest: dict[str, Any],
    run_dir: Path,
    config: dict[str, Any] | None,
) -> None:
    """Record the simplifier prompt and model when the simplified file exists."""
    if not (Path(run_dir) / SIMPLIFIED_NAME).is_file():
        return
    prompts = manifest.get("prompts")
    if isinstance(prompts, dict):
        prompts["simplifier"] = content_sha256(
            resolve_system_prompt("simplifier", config, run_dir)
        )
    spec = _optional_spec(config)
    models = manifest.get("models")
    if spec is not None and isinstance(models, dict):
        models["simplifier"] = {"provider": spec.provider, "model": spec.model}
    files = manifest.get("files")
    if isinstance(files, dict):
        files[SIMPLIFIED_NAME] = SIMPLIFIED_DESC
        if (Path(run_dir) / SIMPLIFY_OUTPUT).is_file():
            files[SIMPLIFY_OUTPUT] = SIMPLIFY_OUTPUT_DESC
        manifest["files"] = dict(sorted(files.items()))


def _assemble(body: str, provenance: str, spec: RoleSpec) -> str:
    line = f"Simplified by {spec.provider}/{spec.model}."
    if provenance:
        text = body.rstrip() + "\n\n" + provenance
        if not text.endswith("\n"):
            text += "\n"
        return text + line + "\n"
    return body.rstrip() + "\n\n" + line + "\n"


def _split(markdown: str) -> tuple[str, str]:
    marker = "\n---\n"
    index = markdown.rfind(marker)
    if index < 0:
        return markdown, ""
    return markdown[:index], markdown[index + 1 :]


def _model_body(text: str) -> str:
    marker = "\n---\n"
    index = text.rfind(marker)
    if index < 0:
        return text.strip()
    tail = text[index:]
    if "Generated by ASGARD" in tail or "Simplified by " in tail:
        return text[:index].strip()
    return text.strip()


def _config(run_dir: Path) -> dict[str, Any]:
    path = run_dir / "config.json"
    if not path.is_file():
        raise ConfigError(_CONFIG)
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        raise ConfigError(_INVALID) from None
    if not isinstance(data, dict):
        raise ConfigError(_INVALID)
    return data


def _settings(config: dict[str, Any]) -> LLMSettings:
    try:
        return LLMSettings.model_validate(config.get("llm"))
    except ValidationError:
        raise ConfigError(_INVALID) from None


def _optional_spec(config: dict[str, Any] | None) -> RoleSpec | None:
    if not isinstance(config, dict):
        return None
    try:
        return _settings(config).resolve("simplifier")
    except ConfigError:
        return None


def _update_manifest(run_dir: Path, config: dict[str, Any]) -> None:
    path = run_dir / "manifest.json"
    if not path.is_file():
        return
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        raise ConfigError(_MANIFEST) from None
    if not isinstance(data, dict):
        raise ConfigError(_MANIFEST)
    apply_simplifier_manifest(data, run_dir, config)
    text = json.dumps(data)
    _replace(path, text)
    copied = run_dir / "bundle" / "output.json"
    if copied.is_file():
        _replace(copied, text)
